import ExcelJS from 'exceljs';
import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { readWorkbook } from '../data/excel';

describe('readWorkbook', () => {
  it('reads every sheet as header-keyed row objects', async () => {
    const wb = new ExcelJS.Workbook();
    const ws = wb.addWorksheet('LP_MODEL');
    ws.addRow(['Service', 'Avg_Duration_Min', 'Max_Hours']);
    ws.addRow(['ENT', 75.5, 12]);
    ws.addRow(['Urology', { formula: '30*2', result: 60 }, 8]);
    const buffer = (await wb.xlsx.writeBuffer()) as ArrayBuffer;

    const sheets = await readWorkbook(buffer);
    expect(sheets.LP_MODEL).toEqual([
      { Service: 'ENT', Avg_Duration_Min: 75.5, Max_Hours: 12 },
      { Service: 'Urology', Avg_Duration_Min: 60, Max_Hours: 8 },
    ]);
  });

  it('parses the dataset workbook generated by the backend', async () => {
    const file = readFileSync('Hospital_OR_Capacity_Dataset.xlsx');
    const buffer = file.buffer.slice(file.byteOffset, file.byteOffset + file.byteLength);
    const sheets = await readWorkbook(buffer as ArrayBuffer);
    expect(Object.keys(sheets)).toEqual(expect.arrayContaining(['RAW_DATA', 'STATS', 'LP_MODEL']));
    expect(sheets.LP_MODEL.length).toBeGreaterThan(0);
    expect(sheets.LP_MODEL[0]).toHaveProperty('Service');
  });
});
